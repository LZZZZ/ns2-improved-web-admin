// The ranked-mod whitelist (docs/CONSTRAINTS.md item 17): whether loading a mod keeps the server
// ranked, for an installed mod (Mods) and for one not installed yet
// (Workshop).
//
// With the mod, the server answers for each mod itself: getinstalledmodslist
// and getmods carry `whitelisted`, from Server.GetIsModWhitelisted(), the
// list the engine read at boot. It covers the hotfix mods too. It never says
// "unknown": if the engine could not read the list at boot, every mod reads
// as not whitelisted.
//
// A stock server says nothing, so the panel uses the copy it ships
// (whitelist.json, regenerated by tools/make-whitelist.py), and says how old
// it is: a mod whitelisted after that date shows as not whitelisted. The
// engine never checks its hotfix mods (NSL Badges, UWE Hotfix 344), so they
// count as whitelisted there.

import { ShieldCheck, ShieldQuestionMark, ShieldX } from "lucide-preact";
import shipped from "../whitelist.json";
import { dateTime } from "./format";
import { StatusIcon } from "./Icon";

export interface Whitelist {
  /** "server": the engine's verdict per mod; "shipped": the panel's own copy. */
  source: "server" | "shipped";
  /** Shipped only: when the copy was read, unix seconds. */
  readAt: number;
  /** Shipped only: decimal workshop ids. */
  ids: Set<string>;
  hotfix: Set<string>;
}

export type WhitelistVerdict = "whitelisted" | "hotfix" | "not" | "unknown";

const shippedList: Whitelist = {
  source: "shipped",
  readAt: Date.parse(shipped.read_at) / 1000,
  ids: new Set(shipped.whitelist.map((m) => m.id)),
  hotfix: new Set(shipped.hotfix.map((m) => m.id)),
};

const serverList: Whitelist = {
  source: "server", readAt: 0, ids: new Set(), hotfix: new Set(),
};

/** The server's verdicts with the mod, else the shipped copy. */
export function useWhitelist(hasMod: boolean): Whitelist {
  return hasMod ? serverList : shippedList;
}

/**
 * Whitelisted or not, by the hex id the rest of the API uses. `server` is the
 * mod's `whitelisted` for that mod; null when the server did not say.
 */
export function whitelistVerdict(list: Whitelist, hexId: string,
                                 server: boolean | null): WhitelistVerdict {
  if (list.source === "server") {
    return server === null ? "unknown" : server ? "whitelisted" : "not";
  }
  if (!/^[0-9a-f]{1,16}$/i.test(hexId)) return "unknown";
  const id = BigInt(`0x${hexId}`).toString();
  if (list.hotfix.has(id)) return "hotfix";
  return list.ids.has(id) ? "whitelisted" : "not";
}

/** Where the list came from, for a tooltip. */
function sourceText(list: Whitelist): string {
  return list.source === "server"
    ? "the whitelist the server read at boot"
    : `the whitelist shipped with the panel, read ${dateTime(list.readAt)}`;
}

export function WhitelistIcon({ list, hexId, server }: {
  list: Whitelist;
  hexId: string;
  server: boolean | null;
}) {
  switch (whitelistVerdict(list, hexId, server)) {
    case "whitelisted":
      return <StatusIcon icon={ShieldCheck} label="whitelisted" tone="ok"
                         title={`ranked servers can load it (${sourceText(list)})`} />;
    case "hotfix":
      return <StatusIcon icon={ShieldCheck} label="whitelisted" tone="ok"
                         title="one of the server's hotfix mods, which ranking never checks" />;
    case "not":
      return <StatusIcon icon={ShieldX} label="not whitelisted" tone="warn"
                         title={list.source === "server"
                           ? `loading it turns ranking off (${sourceText(list)})`
                           : `not on ${sourceText(list)}: loading it turns ranking off, `
                             + "unless it was whitelisted since"} />;
    case "unknown":
      return <StatusIcon icon={ShieldQuestionMark} label="whitelist unknown" tone="dim"
                         title={list.source === "server" ? "the server did not say"
                           : "not a workshop id"} />;
  }
}

/** One line on where the whitelist came from. */
export function WhitelistSource({ list }: { list: Whitelist }) {
  if (list.source === "server") {
    return (
      <p class="muted form-hint whitelist-source" data-source="server">
        Whitelist: the one the server read when it started.
      </p>
    );
  }
  return (
    <p class="muted form-hint whitelist-source" data-source="shipped">
      Whitelist: the copy shipped with the panel, read {dateTime(list.readAt)}
      {" "}({list.ids.size} mods), because a stock server cannot say. A mod
      whitelisted since then shows as not whitelisted.
    </p>
  );
}
